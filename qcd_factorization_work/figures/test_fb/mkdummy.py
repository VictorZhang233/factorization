#!/usr/bin/env python3
"""Generate dummy_labels.tex: dummy targets for every \\cref/\\ref label used in the
figure parts but not defined there, placed in chapters/appendices with the v2
numbering so that the rendered references look realistic (test build only)."""
import re, sys, glob, os

here = os.path.dirname(os.path.abspath(__file__))
files = sys.argv[1:] or sorted(glob.glob(os.path.join(here, 'parts', '*.tex')))
used, defined = [], set()
for f in files:
    s = open(f, encoding='utf-8').read()
    s = re.sub(r'(?<!\\)%.*', '', s)
    for m in re.finditer(r'\\[A-Za-z]*ref\*?\{([^}]*)\}', s):
        for lab in m.group(1).split(','):
            lab = lab.strip()
            if lab and '#' not in lab and lab not in used:
                used.append(lab)
    for m in re.finditer(r'\\label\{([^}]*)\}', s):
        defined.add(m.group(1).strip())
need = [l for l in used if l not in defined]

chap = {'intro': 1, 'qcd': 2, 'prelim': 3, 'ir': 4, 'sudakov': 5, 'ee': 6, 'dis': 7,
        'pdf': 8, 'method': 9, 'disall': 10, 'coll': 11, 'dy': 12, 'thr': 13, 'tmd': 14,
        'scet': 15, 'jets': 16, 'smallx': 17, 'break': 18, 'excl': 19, 'heavy': 20,
        'power': 21, 'lamet': 22, 'yzliu': 23, 'front': 24, 'summary': 25}
figowner = {'ward-identity': 9, 'glauber-contour': 9, 'reduced-dis': 4, 'reduced-ee': 4,
            'dis-oneloop': 7, 'pdf-oneloop': 8, 'pdf-operator': 8, 'momentum-regions': 4,
            'ee-pi-plane': 6, 'vertex-regions': 4, 'sudakov-ff': 5, 'omega-plane': 7,
            'higher-twist': 7, 'soft-eikonal': 3, 'ee-oneloop': 6, 'tmd-staple': 14,
            'glauber-exchange': 12, 'factorization-schematic': 1}
env = {'thm': 'theorem', 'lem': 'lemma', 'prop': 'proposition', 'cor': 'corollary',
       'def': 'definition', 'asm': 'assumption', 'ex': 'example', 'rem': 'remark',
       'conj': 'conjecture'}

def unit(lab):
    pre, _, rest = lab.partition(':')
    key = rest.split('-')[0]
    if pre == 'fig':
        return ('ch', figowner.get(rest, 1))
    if key.startswith('app') and len(key) == 4:
        return ('app', ord(key[3]) - ord('A') + 1)
    return ('ch', chap.get(key, 1))

groups = {}
for l in need:
    groups.setdefault(unit(l), []).append(l)

out = ['% generated by mkdummy.py -- dummy targets for the test build only',
       '\\clearpage\\begingroup\\small']
chs = sorted(k for k in groups if k[0] == 'ch')
apps = sorted(k for k in groups if k[0] == 'app')

def emit(labels):
    for l in labels:
        pre = l.split(':')[0]
        if pre in ('ch','app'):
            continue
        if pre == 'sec':
            out.append('\\section{dummy %s}\\label{%s}' % (l.replace('_', '\\_'), l))
        elif pre == 'fig':
            out.append('\\begin{figure}[h]\\centering\\fbox{dummy}\\caption{dummy %s}\\label{%s}\\end{figure}' % (l, l))
        elif pre == 'tab':
            out.append('\\begin{table}[h]\\centering\\caption{dummy %s}\\label{%s}\\fbox{dummy}\\end{table}' % (l, l))
        elif pre in env:
            out.append('\\begin{%s}\\label{%s}dummy \\texttt{%s}\\end{%s}' % (env[pre], l, l, env[pre]))
        else:
            out.append('\\refstepcounter{equation}\\label{%s}' % l)

for k in chs:
    labs = groups[k]
    out.append('\\setcounter{chapter}{%d}\\addtocounter{chapter}{-1}' % k[1])
    chl = [l for l in labs if l.startswith('ch:')]
    out.append('\\chapter{dummy chapter %d}%s' % (k[1], ''.join('\\label{%s}' % l for l in chl)))
    emit(labs)
if apps:
    out.append('\\appendix')
    for k in apps:
        labs = groups[k]
        out.append('\\setcounter{chapter}{%d}\\addtocounter{chapter}{-1}' % k[1])
        apl = [l for l in labs if l.startswith('app:')]
        out.append('\\chapter{dummy appendix}%s' % ''.join('\\label{%s}' % l for l in apl))
        emit(labs)
out.append('\\endgroup')
open(os.path.join(here, 'dummy_labels.tex'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('dummy labels:', len(need))
for l in need:
    print('  ', l)
