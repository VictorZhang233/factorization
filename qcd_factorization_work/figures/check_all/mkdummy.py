#!/usr/bin/env python3
r"""Figure checker: dummy cross-reference targets for the combined figure test document.

    python3 -I mkdummy.py <FINAL_OUTLINE_v2.md> <out dummy_labels.tex> <figure file> ...

Reads the label registry (section "## 08 Label registry") of FINAL_OUTLINE_v2, collects every
\cref/\Cref/\ref/\autoref/\pageref target used in the figure files, and writes dummy_labels.tex that
defines exactly the targets that the figure files use but do not define themselves, numbered as in the
book (shared [theorem] counter per chapter; chapters 1-25, then \appendix A-Q).  Nothing is typeset.
It also prints every used target that is NOT in the registry (and not defined by a figure file):
those are genuine dangling references.
"""
import re
import sys

TYPE = {'def': 'definition', 'asm': 'assumption', 'thm': 'theorem', 'lem': 'lemma', 'prop': 'proposition',
        'cor': 'corollary', 'conj': 'conjecture', 'rem': 'remark', 'ex': 'example'}
UNITS = ['front'] + ['Ch%02d' % i for i in range(1, 26)] + ['App' + c for c in 'ABCDEFGHIJKLMNOPQ']
KEYS = ['intro', 'qcd', 'prelim', 'ir', 'sudakov', 'ee', 'dis', 'pdf', 'method', 'disall', 'coll', 'dy', 'thr',
        'tmd', 'scet', 'jets', 'smallx', 'break', 'excl', 'heavy', 'power', 'lamet', 'yzliu', 'front', 'summary']

outline, outfile, figfiles = sys.argv[1], sys.argv[2], sys.argv[3:]
text = open(outline, encoding='utf-8').read()
reg_part = text.split('## 08 Label registry')[1].split('## 09 ')[0]
reg = {}          # label -> unit
order = []
unit = None
for line in reg_part.splitlines():
    m = re.match(r'^### (\S+)', line)
    if m:
        unit = m.group(1)
        continue
    if unit is None or unit == 'Assumptions':
        # the Assumptions table repeats asm labels with an owner column; owner rows exist under the units
        if unit == 'Assumptions':
            m = re.match(r'^\| `(asm:[^`]+)` \| (\w+) \|', line)
            if m and m.group(1) not in reg:
                u = m.group(2)
                u = 'Ch%02d' % int(u[2:]) if u.startswith('Ch') else u
                reg[m.group(1)] = u
                order.append(m.group(1))
        continue
    m = re.match(r'^\| `([a-z]+:[^`]+)` \|', line)
    if m:
        lab = m.group(1)
        if lab not in reg:
            reg[lab] = unit
            order.append(lab)
        continue
    # "Optional or continuation tables (not rows): `tab:...`" and optional figure lists
    if 'not rows' in line or line.startswith('Optional'):
        for lab in re.findall(r'`((?:tab|fig|sec):[^`]+)`', line):
            if lab not in reg:
                reg[lab] = unit
                order.append(lab)
# chapter / appendix labels
for i, k in enumerate(KEYS, 1):
    reg.setdefault('ch:' + k, 'Ch%02d' % i)
for c in 'ABCDEFGHIJKLMNOPQ':
    reg.setdefault('app:app' + c, 'App' + c)

used, defined = [], {}
for f in figfiles:
    s = open(f, encoding='utf-8').read()
    s = re.sub(r'(?<!\\)%.*', '', s)
    for m in re.finditer(r'\\[A-Za-z]*ref\*?(?:\[[^\]]*\])?\{([^}]*)\}', s):
        for lab in m.group(1).split(','):
            lab = lab.strip()
            if lab and '#' not in lab and lab not in used:
                used.append(lab)
    for m in re.finditer(r'\\label\{([^}]*)\}', s):
        defined.setdefault(m.group(1).strip(), []).append(f)

need = [l for l in used if l not in defined]
dangling = [l for l in need if l not in reg]
print('targets used:', len(used), '; defined by the figure files:', len([l for l in used if l in defined]),
      '; dummy targets needed:', len(need))
print('DANGLING (used, not defined, not in registry):', dangling if dangling else 'none')

byunit = {}
for l in need:
    byunit.setdefault(reg.get(l, 'front'), []).append(l)

out = ['% generated by mkdummy.py (figure checker) -- dummy cross-reference targets, test document only',
       '\\makeatletter', '\\begingroup', '\\setcounter{chapter}{0}']
for u in UNITS:
    if u == 'front':
        continue
    if u == 'AppA':
        out.append('\\appendix')
    labs = byunit.get(u, [])
    chl = [l for l in labs if l.startswith('ch:') or l.startswith('app:')]
    out.append('\\refstepcounter{chapter}' + ''.join('\\label[%s]{%s}' % ('appendix' if l.startswith('app:') else 'chapter', l) for l in chl) + '% ' + u)
    for lab in labs:
        p = lab.split(':')[0]
        if p in TYPE:
            out.append('\\refstepcounter{theorem}\\label[%s]{%s}' % (TYPE[p], lab))
        elif p == 'sec':
            out.append('\\refstepcounter{section}\\label[%s]{%s}' % ('subappendix' if u.startswith('App') else 'section', lab))
        elif p == 'fig':
            out.append('\\refstepcounter{figure}\\label[figure]{%s}' % lab)
        elif p == 'tab':
            out.append('\\refstepcounter{table}\\label[table]{%s}' % lab)
        elif p in ('ch', 'app'):
            pass
        else:
            out.append('\\refstepcounter{equation}\\label[equation]{%s}' % lab)
for l in dangling:
    out.append('%% DANGLING: %s' % l)
out += ['\\endgroup', '\\makeatother']
open(outfile, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
