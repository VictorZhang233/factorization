# ---- owners and classes from the per-unit table (FIGURES_INDEX_v2 sec. 5) ----
idx = open(IDX, encoding='utf-8').read()
sec5 = idx.split('## 5. Figures per unit')[1].split('## CHANGELOG')[0]
info = {}      # label -> (unit, class)
order = []
for line in sec5.splitlines():
    if not line.startswith('| ') or line.startswith('| unit') or line.startswith('|---') or 'total' in line:
        continue
    cells = [c.strip() for c in line.strip().strip('|').split('|')]
    unit = cells[0]
    for col in (1, 2, 3, 4, 5):
        c = re.sub(r'\(.*?\)', '', cells[col])
        for t in c.split(','):
            t = t.strip()
            if t and t != '—':
                lab = 'fig:' + t
                u = unit
                if lab == 'fig:appE-boost':
                    u = 'App E'
                cl = CLASS[col]
                if lab.startswith('fig:appP-dependency-'):
                    cl = 'required (generated)'
                info[lab] = (u, cl)
                order.append(lab)


def unit_name(u):
    m = re.match(r'Ch(\d+)$', u)
    if m:
        return 'Ch%d `%s`' % (int(m.group(1)), KEYS[int(m.group(1)) - 1])
    return u


# ---- where each label lives ----
where = {}
for rel, short in SOURCES:
    lines = open(os.path.join(W, rel), encoding='utf-8').read().splitlines()
