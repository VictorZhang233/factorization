"""Write the test document test_fd2.tex (one figure per page) or, with an
argument, test_one.tex containing only the figures whose label contains the
argument.  External \\cref targets get dummy environments of the right type,
external \\cite keys a dummy bibliography, so that the log stays clean."""
import sys, os
here = os.path.dirname(os.path.abspath(__file__))
order = [l.strip() for l in open(os.path.join(here, 'split', 'order.txt')) if l.strip()]
ext = [l.strip() for l in open(os.path.join(here, 'split', 'extern.txt')) if l.strip()]
cites = [l.strip() for l in open(os.path.join(here, 'split', 'cites.txt')) if l.strip()]
sel = sys.argv[1] if len(sys.argv) > 1 else None
name = 'test_one.tex' if sel else 'test_fd2.tex'
envs = {'thm': 'theorem', 'lem': 'lemma', 'prop': 'proposition', 'cor': 'corollary', 'conj': 'conjecture',
        'def': 'definition', 'asm': 'assumption', 'ex': 'example', 'rem': 'remark'}
L = ['% !TEX program = xelatex', '% Test document for figset_D.tex (figures/test_fd2), generated by mkdoc.py.',
     r'\input{preamble_fact.tex}', r'\begin{document}', r'\chapter{TikZ 图集 D 测试}']
figs = [f for f in order if (sel is None or sel in f)]
L.append('本测试文档逐页排出 \\texttt{figset\\_D.tex} 中的插图（每页一幅）。交叉引用测试：' +
         '、'.join('\\cref{%s}' % f[:-4].replace('fig_', 'fig:', 1) for f in figs) + '。')
L.append(r'\clearpage')
for f in figs:
    L.append(r'\input{split/%s}\clearpage' % f)
# dummy targets for external references
L.append(r'\chapter{外部引用的占位目标}')
for e in ext:
    pre = e.split(':')[0]
    if pre in envs:
        L.append(r'\begin{%s}[占位]\label{%s}占位。\end{%s}' % (envs[pre], e, envs[pre]))
    elif pre == 'tab':
        L.append(r'\begin{table}[h]\centering\caption{占位}\label{%s}\end{table}' % e)
    elif pre in ('sec', 'ch', 'app'):
        L.append(r'\section{占位}\label{%s}' % e)
    elif pre == 'fig':
        L.append(r'\begin{figure}[h]\centering\caption{占位}\label{%s}\end{figure}' % e)
    else:
        L.append(r'\section{占位}\label{%s}' % e)
if cites:
    L.append(r'\begin{thebibliography}{99}')
    for c in cites:
        L.append(r'\bibitem{%s} 占位文献 \texttt{%s}。' % (c, c))
    L.append(r'\end{thebibliography}')
L.append(r'\end{document}')
open(os.path.join(here, name), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print(name, len(figs), 'figures')
