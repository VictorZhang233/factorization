#!/bin/sh
# Assemble ../figset_C.tex from blocks/, check and split it, write the test
# document (one figure per page, plus dummy targets for the labels that the
# captions \cref), compile twice with XeLaTeX, report warnings, and render
# every page at 110 dpi into png/p-NN.png.
# (printf '%s\n' is used instead of echo: /bin/sh's echo expands \b, \c, ...)
cd "$(dirname "$0")" || exit 1
{ cat blocks/00_header.tex; for f in blocks/[0-9][0-9]_fig_*.tex; do printf '\n'; cat "$f"; done; } > ../figset_C.tex
python3 -I split_figures.py || { printf '%s\n' "SPLIT ERROR"; exit 1; }
{
  printf '%s\n' '% !TEX program = xelatex'
  printf '%s\n' '% Test document for ../figset_C.tex (agent figC), generated by build.sh.'
  printf '%s\n' '\input{preamble_fact.tex}'
  printf '%s\n' '\begin{document}'
  printf '%s\n' '\chapter{TikZ 图集 C 测试}'
  printf '%s' '本测试文档逐页排出 \texttt{figset\_C.tex} 中的全部插图（每页一幅）。交叉引用测试：'
  sed -e 's/\.tex$//' -e 's/^fig_/fig:/' split/order.txt | awk '{printf "%s\\cref{%s}", (NR>1?"、":""), $0} END {print "。"}'
  printf '%s\n' '\clearpage'
  while read -r f; do printf '%s\n' "\\input{split/$f}\\clearpage"; done < split/order.txt
  printf '%s\n' '\section{交叉引用目标（仅供测试）}'
  printf '%s\n' '\begin{lemma}\label{lem:dy-poles-orientation}测试目标。\end{lemma}'
  printf '%s\n' '\begin{proposition}\label{prop:dy-abelian-model}测试目标。\end{proposition}'
  printf '%s\n' '\begin{proposition}\label{prop:dy-eikonal-twogluon}测试目标。\end{proposition}'
  printf '%s\n' '\begin{theorem}\label{thm:thr-refactorization}测试目标。\end{theorem}'
  printf '%s\n' '\begin{remark}\label{rem:thr-prescriptions}测试目标。\end{remark}'
  printf '%s\n' '\begin{proposition}\label{prop:jets-sw}测试目标。\end{proposition}'
  printf '%s\n' '\begin{proposition}\label{prop:jets-ngl}测试目标。\end{proposition}'
  printf '%s\n' '\begin{proposition}\label{prop:jets-sll}测试目标。\end{proposition}'
  printf '%s\n' '\begin{theorem}\label{thm:smallx-bk}测试目标。\end{theorem}'
  printf '%s\n' '\begin{conjecture}\label{conj:smallx-saturation}测试目标。\end{conjecture}'
  printf '%s\n' '\begin{figure}[htbp]\centering\fbox{测试}\caption{测试目标。}\label{fig:bfkl-ladder}\end{figure}'
  printf '%s\n' '\begin{figure}[htbp]\centering\fbox{测试}\caption{测试目标。}\label{fig:glauber-contour}\end{figure}'
  printf '%s\n' '\begin{figure}[htbp]\centering\fbox{测试}\caption{测试目标。}\label{fig:method-glauber-direction}\end{figure}'
  printf '%s\n' '\begin{thebibliography}{9}'
  grep -o '\\cite{[^}]*}' ../figset_C.tex | sed -e 's/\\cite{//' -e 's/}//' | tr ',' '\n' | sort -u | while read -r k; do printf '%s\n' "\\bibitem{${k}} Test entry \\texttt{${k}}."; done
  printf '%s\n' '\end{thebibliography}'
  printf '%s\n' '\end{document}'
} > test_fc.tex
xelatex -interaction=nonstopmode -halt-on-error test_fc.tex > build.log 2>&1 || { printf '%s\n' "LaTeX ERROR"; grep -n -A8 "^!" test_fc.log | head -60; exit 1; }
xelatex -interaction=nonstopmode -halt-on-error test_fc.tex > build.log 2>&1 || { printf '%s\n' "LaTeX ERROR (2nd run)"; grep -n -A8 "^!" test_fc.log | head -60; exit 1; }
printf '%s\n' "--- warnings (Overfull/Underfull/undefined/multiply/Missing character):"
grep -n -E "Overfull|Underfull|undefined|multiply|Missing character|Warning: Reference" test_fc.log | head -30
mkdir -p png; rm -f png/p-*.png; pdftoppm -r 110 -png test_fc.pdf png/p
printf 'pages: %s\n' "$(ls png/p-*.png | wc -l | tr -d ' ')"
