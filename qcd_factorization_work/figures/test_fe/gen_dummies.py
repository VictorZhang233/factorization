"""Test-document helper: create dummy targets for every non-figure label that
the split figure blocks reference with \\cref, and a dummy bibliography for
every \\cite key (so that the test PDF shows resolved references).
Writes dummy_targets.tex and dummy_bib.tex next to this script."""
import re, os
here = os.path.dirname(os.path.abspath(__file__))
order = open(os.path.join(here, 'split', 'order.txt')).read().split()
refs, cites, figrefs, figdefs = [], [], [], set()
for fn in order:
    body = open(os.path.join(here, 'split', fn), encoding='utf-8').read()
    figdefs.update(re.findall(r'\\label\{(fig:[^}]*)\}', body))
    for grp in re.findall(r'\\[cC]ref\{([^}]*)\}', body):
        for l in grp.split(','):
            l = l.strip()
            if l.startswith('fig:'):
                if l not in figrefs:
                    figrefs.append(l)
            elif l and l not in refs:
                refs.append(l)
    for grp in re.findall(r'\\cite(?:\[[^]]*\])?\{([^}]*)\}', body):
        for k in grp.split(','):
            k = k.strip()
            if k and k not in cites:
                cites.append(k)
env = {'thm': 'theorem', 'prop': 'proposition', 'lem': 'lemma', 'cor': 'corollary',
       'conj': 'conjecture', 'def': 'definition', 'asm': 'assumption', 'ex': 'example',
       'rem': 'remark'}
out = ['% generated by gen_dummies.py (test document only)', '\\section{交叉引用的占位目标}']
secs = [l for l in refs if l.split(':')[0] == 'sec']
for l in refs:
    p = l.split(':')[0]
    if p in env:
        out.append('\\begin{%s}[占位：\\texttt{%s}]\\label{%s}占位。\\end{%s}' % (env[p], l, l, env[p]))
for l in secs:
    out.append('\\section{占位节：\\texttt{%s}}\\label{%s}' % (l, l))
# figures owned by other units (referenced but not defined in this set): caption-only targets
for l in figrefs:
    if l not in figdefs:
        out.append('\\begin{center}\\captionof{figure}{占位：外部图 \\texttt{%s}}\\label{%s}\\end{center}' % (l, l))
open(os.path.join(here, 'dummy_targets.tex'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
bib = ['% generated by gen_dummies.py (test document only)', '\\begin{thebibliography}{99}']
for k in cites:
    bib.append('\\bibitem{%s} 占位文献 \\texttt{%s}。' % (k, k))
if not cites:
    bib.append('\\bibitem{none} 无。')
bib.append('\\end{thebibliography}')
open(os.path.join(here, 'dummy_bib.tex'), 'w', encoding='utf-8').write('\n'.join(bib) + '\n')
print('dummy targets:', refs, '+ external figures:', [l for l in figrefs if l not in figdefs])
print('dummy cites:', cites)
