#!/bin/sh
# Rebuild ../figset_E.tex from blocks/, check the delimiters, write the test
# document (one figure per page), compile it twice with XeLaTeX and render
# every page at 110 dpi into png/p-NN.png.
# (printf '%s\n' is used instead of echo: /bin/sh's echo expands \b, \c, ...)
cd "$(dirname "$0")" || exit 1
{ cat blocks/00_header.tex; for f in blocks/[0-9][0-9]_fig_*.tex; do printf '\n'; cat "$f"; done; } > ../figset_E.tex
python3 -I split_figures.py || { printf '%s\n' "SPLIT ERROR"; exit 1; }
python3 -I gen_dummies.py || { printf '%s\n' "DUMMY ERROR"; exit 1; }
{
  printf '%s\n' '% !TEX program = xelatex'
  printf '%s\n' '% Test document for figset_E.tex (figures/test_fe), generated by build.sh.'
  printf '%s\n' '\input{preamble_fact.tex}'
  printf '%s\n' '\begin{document}'
  printf '%s\n' '\chapter{TikZ 图集 E 测试}'
  printf '%s' '本测试文档逐页排出 \texttt{figset\_E.tex} 中的全部插图（每页一幅）。交叉引用测试：'
  sed -e 's/\.tex$//' -e 's/^fig_/fig:/' split/order.txt | awk '{printf "%s\\cref{%s}", (NR>1?"、":""), $0} END {print "。"}'
  printf '%s\n' '\input{dummy_targets.tex}'
  printf '%s\n' '\clearpage'
  while read -r f; do printf '%s\n' "\\input{split/$f}\\clearpage"; done < split/order.txt
  printf '%s\n' '\input{dummy_bib.tex}'
  printf '%s\n' '\end{document}'
} > test_fe.tex
xelatex -interaction=nonstopmode -halt-on-error test_fe.tex > build.log 2>&1 || { printf '%s\n' "LaTeX ERROR"; grep -n -A8 "^!" test_fe.log | head -60; exit 1; }
xelatex -interaction=nonstopmode -halt-on-error test_fe.tex > build.log 2>&1 || { printf '%s\n' "LaTeX ERROR (2nd run)"; grep -n -A8 "^!" test_fe.log | head -60; exit 1; }
grep -n -E "Overfull|Underfull|undefined|multiply|Missing character|Error" test_fe.log | head -30
rm -f png/p-*.png; pdftoppm -r 110 -png test_fe.pdf png/p
printf 'pages: %s\n' "$(ls png/p-*.png | wc -l | tr -d ' ')"
