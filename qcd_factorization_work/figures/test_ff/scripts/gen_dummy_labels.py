r"""Write dummy_labels.tex: every statement label of the FINAL_OUTLINE_v2 registry, numbered as in the book
(shared [theorem] counter per chapter; chapters 1-25, then \appendix A-Q), defined with cleveref's
\label[<type>]{...} after \refstepcounter{theorem}, without typesetting anything.  Used only by the test
document of figure set F so that \cref inside figures resolves to realistic printed numbers.

    python3 -I gen_dummy_labels.py outline.json dummy_labels.tex
"""
import sys, json, glob, re, os

TYPE = {'def': 'definition', 'asm': 'assumption', 'thm': 'theorem', 'lem': 'lemma', 'prop': 'proposition',
        'cor': 'corollary', 'conj': 'conjecture', 'rem': 'remark', 'ex': 'example'}
UNITS = ['Ch%02d' % i for i in range(1, 26)] + ['App' + c for c in 'ABCDEFGHIJKLMNOPQ']
d = json.load(open(sys.argv[1], encoding='utf-8'))
# figure labels drawn in this figure set (defined by the test document itself; not duplicated here)
own = set()
for f in glob.glob(os.path.join(os.path.dirname(os.path.abspath(sys.argv[2])), 'blocks', '*_fig_*.tex')):
    own |= set(re.findall(r'\\label\{(fig:[^}]*)\}', open(f, encoding='utf-8').read()))
rows = {}
for r in d['registry']:
    rows.setdefault(r['unit'], []).append(r['label'])
out = ['% generated by scripts/gen_dummy_labels.py -- dummy statement labels (test document only)',
       '\\makeatletter', '\\begingroup', '\\setcounter{chapter}{0}']
n = 0
for u in UNITS:
    if u == 'AppA':
        out.append('\\appendix')
    out.append('\\refstepcounter{chapter}% ' + u)
    for lab in rows.get(u, []):
        p = lab.split(':')[0]
        if p in TYPE:
            out.append('\\refstepcounter{theorem}\\label[%s]{%s}' % (TYPE[p], lab))
            n += 1
        elif p == 'sec':
            out.append('\\refstepcounter{section}\\label[section]{%s}' % lab)
        elif p == 'fig' and lab not in own:
            out.append('\\refstepcounter{figure}\\label[figure]{%s}' % lab)
        elif p == 'tab':
            out.append('\\refstepcounter{table}\\label[table]{%s}' % lab)
out += ['\\endgroup', '\\makeatother']
open(sys.argv[2], 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('labels:', n)
