#!/bin/sh
# Rebuild ../figset_F.tex from blocks/, check the delimiters, write the test document
# (one figure per page, dummy statement labels at the end so that \cref resolves),
# compile twice with XeLaTeX and render every figure page at 110 dpi into png/p-NN.png.
cd "$(dirname "$0")" || exit 1
{ cat blocks/00_header.tex; for f in blocks/[0-9][0-9]_fig_*.tex; do printf '\n'; cat "$f"; done; } > ../figset_F.tex
# delimiter check
python3 -I scripts/check_blocks.py ../figset_F.tex || { printf '%s\n' "BLOCK ERROR"; exit 1; }
{
  printf '%s\n' '% !TEX program = xelatex'
  printf '%s\n' '% Test document for figures/figset_F.tex (agent figF), generated by build.sh.'
  printf '%s\n' '\input{preamble_fact.tex}'
  printf '%s\n' '\begin{document}'
  printf '%s\n' '\chapter{TikZ 图集 F 测试}'
  printf '%s' '本测试文档逐页排出 \texttt{figset\_F.tex} 中的全部插图（每页一幅）。交叉引用测试：'
  grep -h '^%%% BEGIN' blocks/[0-9][0-9]_fig_*.tex | sed 's/^%%% BEGIN //' | awk '{printf "%s\\cref{%s}", (NR>1?"、":""), $0} END {print "。"}'
  printf '%s\n' '\clearpage'
  for f in blocks/[0-9][0-9]_fig_*.tex; do printf '%s\n' "\\input{$f}\\clearpage"; done
  printf '%s\n' '\input{dummy_labels.tex}\noindent（测试用虚拟标签页。）'
  printf '%s\n' '\end{document}'
} > test_figset_F.tex
xelatex -interaction=nonstopmode -halt-on-error test_figset_F.tex > build.log 2>&1 || { printf '%s\n' "LaTeX ERROR"; grep -n -A8 "^!" test_figset_F.log | head -40; exit 1; }
xelatex -interaction=nonstopmode -halt-on-error test_figset_F.tex > build.log 2>&1 || { printf '%s\n' "LaTeX ERROR (2nd run)"; grep -n -A8 "^!" test_figset_F.log | head -40; exit 1; }
grep -n -E "Overfull|Underfull|undefined|multiply|Missing character|LaTeX Warning" test_figset_F.log | grep -v "Underfull \\\\vbox" | head -30
rm -f png/p-*.png; pdftoppm -r 110 -png test_figset_F.pdf png/p
printf 'pages: %s\n' "$(ls png/p-*.png | wc -l | tr -d ' ')"
