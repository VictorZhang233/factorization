"""X2 / recession.py -- exact check that a tropical exponent psi_a decreases strictly along every recession ray of a 2D cell.
psi_a^inf(r) = <a+w, r> - sum_k max_b <b, r>  (homogeneous part).  On a 2D cone generated by rays r1, r2 (r = (1-t) r1 + t r2),
psi^inf is concave piecewise linear in t; its maximum is at t in {0,1} or at a tie point of two monomials of one factor.
Returns the exact maximum (Fraction) over the normalised cone cross-section; must be < 0."""
import itertools
from fractions import Fraction as Fr

def cone_rays(cons):
    """extreme rays of {r in R^2 : g.r <= 0 for (g, h) in cons}; returns list of rays (None if cone = {0}),
    or 'full'/'halfplane' cases handled by returning a ray set covering them."""
    G = [(Fr(g[0]).limit_denominator(1000), Fr(g[1]).limit_denominator(1000)) for g, _ in cons]
    cand = []
    for (a, b) in G:
        for s in (1, -1):
            cand.append((s*b, -s*a))          # direction along the boundary line a x + b y = 0
    if not G:
        cand = [(Fr(1), Fr(0)), (Fr(0), Fr(1)), (Fr(-1), Fr(0)), (Fr(0), Fr(-1))]
    rays = [r for r in cand if all(a*r[0] + b*r[1] <= 0 for (a, b) in G) and (r[0] != 0 or r[1] != 0)]
    # deduplicate by direction
    out = []
    for r in rays:
        if not any(r[0]*q[1] - r[1]*q[0] == 0 and r[0]*q[0] + r[1]*q[1] > 0 for q in out):
            out.append(r)
    return out

def psi_inf(a, w, forms, r):
    val = (Fr(int(a[0])) + Fr(w[0]))*r[0] + (Fr(int(a[1])) + Fr(w[1]))*r[1]
    for fl in forms:
        val -= max(Fr(int(b[0]))*r[0] + Fr(int(b[1]))*r[1] for b in fl)
    return val

def max_slope(a, w, forms, cons):
    rays = cone_rays(cons)
    if not rays:
        return None            # bounded cell
    best = None
    pairs = [(r, r) for r in rays] + list(itertools.combinations(rays, 2))
    for r1, r2 in pairs:
        # only combine rays spanning a sector inside the cone (angle < pi): check the midpoint is feasible
        ts = {Fr(0), Fr(1)}
        for fl in forms:
            for b1, b2 in itertools.combinations(fl, 2):
                # tie: <b1-b2, (1-t) r1 + t r2> = 0
                d1 = (int(b1[0]) - int(b2[0]))*r1[0] + (int(b1[1]) - int(b2[1]))*r1[1]
                d2 = (int(b1[0]) - int(b2[0]))*r2[0] + (int(b1[1]) - int(b2[1]))*r2[1]
                if d1 != d2:
                    t = Fr(d1)/(d1 - d2)
                    if 0 <= t <= 1: ts.add(t)
        for t in ts:
            r = ((1 - t)*r1[0] + t*r2[0], (1 - t)*r1[1] + t*r2[1])
            if r == (0, 0): continue
            nrm = abs(r[0]) + abs(r[1])
            val = psi_inf(a, w, forms, r)/nrm
            best = val if (best is None or val > best) else best
    return best
