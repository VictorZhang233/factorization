"""X2 fix round 2 / r2_cert_audit.py -- audit of the archived TRIANGLE certificates (logs/r1_triangle_certificates.json)
for the face-dimension defect of r1_lptools._certify (review r2_2 F4): the bound dim F <= (n+K) - rank(A_S) is valid only
if the exact dual is positive on the whole floating support S (then S+ = S).  We check every archived monomial
certificate for exact zero dual entries.  (The rows themselves are regenerated by r1_triangle_recert.py; with no zero
entries the r1 bound coincides with the repaired bound of r2_lptools.)"""
import sys, os, json
from fractions import Fraction as Fr
HERE = os.path.dirname(os.path.abspath(__file__))
A = json.load(open(os.path.join(os.path.dirname(HERE), 'logs', 'r1_triangle_certificates.json')))
n_cert = n_mono = n_zero = 0; dims = {}
def walk(o, path=''):
    global n_cert, n_mono, n_zero
    if isinstance(o, dict):
        if 'certs' in o and isinstance(o['certs'], list):
            n_cert += 1
            for c in o['certs']:
                n_mono += 1
                if any(Fr(v) == 0 for v in c['dual'].values()):
                    n_zero += 1
                dims[c['dim_bound']] = dims.get(c['dim_bound'], 0) + 1
        for k, v in o.items():
            walk(v, path + '/' + str(k))
    elif isinstance(o, list):
        for i, v in enumerate(o):
            walk(v, path + f'[{i}]')
walk(A)
print(f"triangle archive: {n_cert} piece certificates, {n_mono} monomial certificates, exact zero dual entries on S: {n_zero}")
print(f"distribution of the (r1) face-dimension bounds: {dict(sorted(dims.items()))}")
print("=> S+ = S for every archived triangle certificate; the archived L-power bounds are valid as stated." if n_zero == 0
      else "=> some certificates need the repaired bound")
