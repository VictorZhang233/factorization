#!/bin/sh
# Rebuild figures3.tex from blocks/, check the delimiters, write the test
# document (one figure per page), compile it twice with XeLaTeX and render
# every page at 110 dpi into png/p-NN.png.
# (printf '%s\n' is used instead of echo: /bin/sh's echo expands \b, \c, ...)
cd "$(dirname "$0")" || exit 1
{ cat blocks/00_header.tex; for f in blocks/[0-9][0-9]_fig_*.tex; do printf '\n'; cat "$f"; done; } > figures3.tex
python3 -I split_figures.py || { printf '%s\n' "SPLIT ERROR"; exit 1; }
{
  printf '%s\n' '% !TEX program = xelatex'
  printf '%s\n' '% Test document for figures3.tex (research/tikz3), generated by build.sh.'
  printf '%s\n' '\input{preamble_fact.tex}'
  printf '%s\n' '\begin{document}'
  printf '%s\n' '\chapter{TikZ 图集 3 测试}'
  printf '%s' '本测试文档逐页排出 \texttt{figures3.tex} 中的全部插图（每页一幅）。交叉引用测试：'
  sed -e 's/\.tex$//' -e 's/^fig_/fig:/' split/order.txt | awk '{printf "%s\\cref{%s}", (NR>1?"、":""), $0} END {print "。"}'
  printf '%s\n' '\clearpage'
  while read -r f; do printf '%s\n' "\\input{split/$f}\\clearpage"; done < split/order.txt
  printf '%s\n' '\end{document}'
} > test_figures3.tex
xelatex -interaction=nonstopmode -halt-on-error test_figures3.tex > build.log 2>&1 || { printf '%s\n' "LaTeX ERROR"; grep -n -A6 "^!" test_figures3.log | head -40; exit 1; }
xelatex -interaction=nonstopmode -halt-on-error test_figures3.tex > build.log 2>&1 || { printf '%s\n' "LaTeX ERROR (2nd run)"; exit 1; }
grep -n -E "Overfull|Underfull|undefined|multiply|Missing character" test_figures3.log | head -20
rm -f png/p-*.png; pdftoppm -r 110 -png test_figures3.pdf png/p
printf 'pages: %s\n' "$(ls png/p-*.png | wc -l | tr -d ' ')"
