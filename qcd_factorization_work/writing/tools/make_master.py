#!/usr/bin/env python3
r"""make_master.py -- write the master driver of the monograph (build/qcd_factorization.tex).

    python3 -I make_master.py --src build/src --out build/qcd_factorization.tex
            [--src-rel src] [--appP-rel appP] [--bib refs_final]
            [--front-order front-toc|toc-front] [--summary-part page|toc|none] [--appendix-part page|toc|none]

The driver: \input{preamble_fact.tex}, \usepackage{longtable} (WRITER_SPEC_v2 §6.13, FINAL_OUTLINE_v2 App P §P.7),
pdftitle, title page (title, empty author, \date{\today}, as in the Furry monograph), front matter, table of contents,
main matter with the seven \part dividers of WRITER_SPEC_v2 §1.1 note 4 (the Part VII preface part7_preface.tex, written
by the Ch22 writer, is input right after the Part VII divider), Ch25 after Part VII, \appendix before
App A, App P = the written introduction appP_blueprint.tex followed by the generated sections of blueprint_gen.py
(register, status, uses, graphs a-h, checks; §P.2-§P.6), bibliography (unsrt, refs_final.bib).

Units whose file does not exist in --src are skipped with a comment (partial books).  Chapter and part counters are
set explicitly before every unit, so that printed numbers stay those of the final book when units are missing.

Decisions (defaults; see the integration report):
  * front-toc: title page -> front.tex (摘要、阅读指南、严格性标签、记号与约定; \chapter* with \addcontentsline,
    roman page numbers) -> table of contents -> main matter.  Same order as the Furry monograph (abstract before the
    TOC) and as Chinese book practice (摘要/前言 before 目录); the TOC still lists the front sections first.
  * summary-part page: an unnumbered part divider 「总结」 before Ch25 (with TOC entry and PDF bookmark), so that the
    book-wide summary is not filed under Part VII 前沿进展 (the outline itself has a top-level heading 「总结」).
  * appendix-part page: an unnumbered part divider 「附录」 before App A, so that the appendices are not filed under
    「总结」 in the TOC and in the bookmarks.
"""
import os, sys, argparse
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import booklib as B

BOOK_TITLE = 'QCD 因子化定理：严格证明、全阶论证与适用边界'
APPP_TITLE = '形式化蓝图：假设登记表、依赖图与状态表'
# part prefaces written by unit writers (not units): input right after the part divider
PART_PREFACES = B.PART_PREFACE_FILES
GENERATED = ['appP_register.tex', 'appP_status.tex', 'appP_uses.tex'] + ['appP_graph_%s.tex' % g for g in 'abcdefgh'] + \
            ['appP_checks.tex']


def unnumbered_part(title, mode):
    if mode == 'none':
        return ['%% (no part divider for 「%s」)' % title]
    if mode == 'toc':
        return ['\\cleardoublepage\\phantomsection\\addcontentsline{toc}{part}{%s}%% TOC/bookmark entry only' % title]
    return ['\\cleardoublepage\\phantomsection\\addcontentsline{toc}{part}{%s}' % title, '\\part*{%s}' % title]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--src', required=True, help='directory with the unit files (e.g. build/src)')
    ap.add_argument('--out', required=True, help='master file to write (e.g. build/qcd_factorization.tex)')
    ap.add_argument('--src-rel', default=None, help='path of --src relative to the master (default: computed)')
    ap.add_argument('--appP-rel', default='appP', help='directory of the generated App P files relative to the master')
    ap.add_argument('--bib', default='refs_final')
    ap.add_argument('--front-order', default='front-toc', choices=['front-toc', 'toc-front'])
    ap.add_argument('--summary-part', default='page', choices=['page', 'toc', 'none'])
    ap.add_argument('--appendix-part', default='page', choices=['page', 'toc', 'none'])
    a = ap.parse_args()
    mdir = os.path.dirname(os.path.abspath(a.out))
    rel = a.src_rel if a.src_rel is not None else os.path.relpath(os.path.abspath(a.src), mdir)
    if ' ' in rel:
        sys.exit('make_master: the relative source path "%s" contains a space (TeX would fail)' % rel)
    present = {u for u in B.UNITS if os.path.exists(os.path.join(a.src, B.UNIT_FILE[u]))}
    known = set(B.FILE_UNIT) | set(f for v in PART_PREFACES.values() for f in v)
    others = sorted(f for f in os.listdir(a.src) if f.endswith('.tex') and f not in known) if os.path.isdir(a.src) else []

    L = []
    w = L.append
    w('% !TEX program = xelatex')
    w('%% 《%s》 -- master driver generated by writing/tools/make_master.py; do not edit by hand.' % BOOK_TITLE)
    w('% Build: build/build.sh (figure sync, merged bibliography, generated App P, xelatex/bibtex passes, log summary).')
    w('%% Units present: %d of %d.' % (len(present), len(B.UNITS)))
    if others:
        w('% Files in the source directory that are not units (ignored): ' + ', '.join(others))
    w('\\input{preamble_fact.tex}')
    w('\\usepackage{longtable}   % generated App P tables (WRITER_SPEC_v2 §6.13); preamble_fact.tex is not modified')
    w('\\hypersetup{pdftitle={%s}}' % BOOK_TITLE)
    w('\\title{QCD 因子化定理：\\\\[0.6ex]严格证明、全阶论证与适用边界}')
    w('\\author{}')
    w('\\date{\\today}')
    w('')
    w('\\begin{document}')
    w('\\pagenumbering{Alph}   % title page gets its own page anchor (no duplicate page.i destination)')
    w('\\maketitle')
    w('\\frontmatter')

    def inp(u):
        f = B.UNIT_FILE[u]
        if u in present:
            return ['\\input{%s/%s}' % (rel, f)]
        return ['%% [not yet written] %s (%s)' % (f, u)]
    front = inp('front')
    toc = ['\\tableofcontents']
    for x in (front + toc if a.front_order == 'front-toc' else toc + front):
        w(x)
    w('')
    w('\\mainmatter')
    for p in range(1, 8):
        units = [u for u in B.UNITS if B.UNIT_PART[u] == p]
        if any(u in present for u in units):
            w('')
            w('\\setcounter{part}{%d}%% keeps part numbers when parts are missing' % (p - 1))
            w('\\part{%s}' % B.PART_TITLE[p])
            for pf in PART_PREFACES.get(p, []):
                if os.path.exists(os.path.join(a.src, pf)):
                    w('\\input{%s/%s}%% part preface (not a unit; no labels)' % (rel, pf))
                else:
                    w('%% [part preface %s not present]' % pf)
        else:
            w('')
            w('%% [part %d 「%s」 omitted: no unit present]' % (p, B.PART_TITLE[p]))
        for u in units:
            if u in present:
                w('\\setcounter{chapter}{%d}' % (int(u[2:]) - 1))
            for x in inp(u):
                w(x)
    w('')
    if 'Ch25' in present:
        for x in unnumbered_part('总结', a.summary_part):
            w(x)
        w('\\setcounter{chapter}{24}')
    for x in inp('Ch25'):
        w(x)
    w('')
    apps = [u for u in B.UNITS if B.is_appendix(u)]
    w('\\appendix')
    for x in unnumbered_part('附录', a.appendix_part):
        w(x)
    for u in apps:
        k = ord(u[3]) - ord('A') + 1
        if u == 'AppP':
            w('\\setcounter{chapter}{%d}' % (k - 1))
            if u in present:
                w('\\input{%s/%s}' % (rel, B.UNIT_FILE[u]))
            else:
                w('%% [not yet written] %s: fallback chapter heading for the generated sections' % B.UNIT_FILE[u])
                w('\\chapter{%s}\\label{app:appP}' % APPP_TITLE)
            w('% generated App P sections (writing/tools/blueprint_gen.py; FINAL_OUTLINE_v2 App P §P.2-§P.6)')
            for g in GENERATED:
                w('\\InputIfFileExists{%s/%s}{}{\\typeout{*** generated App P file %s missing: run blueprint_gen.py ***}}'
                  % (a.appP_rel, g, g))
            continue
        if u in present:
            w('\\setcounter{chapter}{%d}' % (k - 1))
        for x in inp(u):
            w(x)
    w('')
    w('\\backmatter')
    w('\\cleardoublepage\\phantomsection\\label{book:bibstart}%')
    w('\\bibliographystyle{unsrt}')
    w('\\bibliography{%s}' % a.bib)
    w('\\end{document}')
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write('\n'.join(L) + '\n')
    print('make_master: %s (%d of %d units present%s)' % (a.out, len(present), len(B.UNITS),
                                                           '; not units: ' + ', '.join(others) if others else ''))


if __name__ == '__main__':
    main()
