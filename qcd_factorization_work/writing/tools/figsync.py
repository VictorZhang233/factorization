#!/usr/bin/env python3
r"""figsync.py -- re-synchronise the figure blocks of the unit files with the figure sources (LEAD_DECISIONS LA-10).

    python3 -I figsync.py --chapters chapters --root <work dir>              # dry run: report only
    python3 -I figsync.py --chapters chapters --root <work dir> --apply --out build/src [--normalize-refs]
            [--report build/figsync_report.txt]

For every `%%% BEGIN fig:X` ... `%%% END fig:X` block of the unit files (all *.tex files of --chapters), the block is
replaced by the current block of the figure sources.  Source map: the "source" column of figures/FIGURES_STATUS.md
(`file`:line of the BEGIN delimiter) plus all `%%% BEGIN/END` blocks of figures/figset_*.tex and
research/tikz{1,2,3}/figures{1,2,3}.tex; a block is always located by its delimiters, never by the line number.
The App P graphs fig:appP-dependency, fig:appP-dependency-b ... -h are generated by blueprint_gen.py: a block with one
of these labels in a unit file is removed from the copy (replaced by a comment), since build/appP/ defines the label.

Report: blocks that differ from the source (with the first differing line), blocks missing in the sources, duplicate
labels (in the units or in the sources), unterminated or mismatched delimiters, figure labels defined outside blocks.

--apply writes a COPY of all *.tex files of --chapters into --out (stale *.tex files in --out are removed); it never
writes into the chapters directory.  --normalize-refs (copy only) removes the whitespace inside the label lists of
\cref, \Cref, \cpageref, \labelcref, \crefrange and \uses: cleveref does not trim spaces, so `\cref{a, b}` or a
\uses list broken across lines prints "??" for every label after the first (verified with the preamble).
Exit code: 0 (findings are reported, never fatal) unless --chapters does not exist.
"""
import os, re, sys, glob, shutil, argparse, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import booklib as B

BEGIN_RE = re.compile(r'^\s*(%{2,})\s*BEGIN\s+(fig:[^\s%]+)\s*$')
END_RE = re.compile(r'^\s*(%{2,})\s*END\s+(fig:[^\s%]+)\s*$')
LIST_CMD_RE = re.compile(r'(\\(?:cref|Cref|cpageref|Cpageref|labelcref|crefrange|Crefrange|uses)\*?\s*\{)([^{}]*)(\})')


def blocks_of(text, fname, problems):
    """[(label, begin_line, end_line, block_text)] of a file; delimiter problems appended to problems."""
    lines = text.split('\n')
    out, cur = [], None
    for i, line in enumerate(lines):
        m = BEGIN_RE.match(line)
        if m:
            if len(m.group(1)) != 3:
                problems.append('%s:%d: non-standard delimiter "%s BEGIN %s" (WRITER_SPEC_v2 §8: %%%%%% BEGIN)' % (
                    fname, i + 1, m.group(1), m.group(2)))
            if cur is not None:
                problems.append('%s:%d: BEGIN %s inside the open block %s (line %d)' % (fname, i + 1, m.group(2), cur[0], cur[1]))
            cur = (m.group(2), i + 1)
            continue
        m = END_RE.match(line)
        if m:
            if len(m.group(1)) != 3:
                problems.append('%s:%d: non-standard delimiter "%s END %s"' % (fname, i + 1, m.group(1), m.group(2)))
            if cur is None:
                problems.append('%s:%d: END %s without BEGIN' % (fname, i + 1, m.group(2)))
                continue
            if m.group(2) != cur[0]:
                problems.append('%s:%d: END %s closes the block BEGIN %s (line %d)' % (fname, i + 1, m.group(2), cur[0], cur[1]))
            out.append((cur[0], cur[1], i + 1, '\n'.join(lines[cur[1] - 1:i + 1])))
            cur = None
    if cur is not None:
        problems.append('%s:%d: BEGIN %s without END' % (fname, cur[1], cur[0]))
    return out


def norm_block(t):
    """Comparison form: trailing blanks removed; delimiter lines written with exactly three '%'."""
    lines = [re.sub(r'^\s*%{2,}\s*(BEGIN|END)\s+', r'%%% \1 ', l.rstrip()) for l in t.replace('\r\n', '\n').split('\n')]
    return '\n'.join(lines).strip('\n')


def first_diff(a, b):
    la, lb = a.split('\n'), b.split('\n')
    for i in range(max(len(la), len(lb))):
        x = la[i] if i < len(la) else '<missing>'
        y = lb[i] if i < len(lb) else '<missing>'
        if x != y:
            return i + 1, x[:90], y[:90]
    return None


def source_index(root, status_path, problems):
    """label -> dict(file, line, text, status_file) from FIGURES_STATUS.md + all delimiter blocks of the sources."""
    status = {}
    if os.path.exists(status_path):
        for line in B.read_text(status_path).split('\n'):
            m = re.match(r'^\|\s*`(fig:[^`]+)`\s*\|(.*)$', line)
            if m:
                ms = re.search(r'`([^`]+\.tex)`:(\d+)', m.group(2))
                if ms:
                    status[m.group(1)] = (ms.group(1), int(ms.group(2)))
    files = set(f for f, _ in status.values())
    files |= set(os.path.relpath(p, root) for p in glob.glob(os.path.join(root, 'figures', 'figset_*.tex')))
    for k in (1, 2, 3):
        files.add(os.path.join('research', 'tikz%d' % k, 'figures%d.tex' % k))
    found = collections.defaultdict(list)
    for rel in sorted(files):
        p = os.path.join(root, rel)
        if not os.path.exists(p):
            problems.append('source file %s (named in FIGURES_STATUS.md) does not exist' % rel)
            continue
        for (lab, b, e, txt) in blocks_of(B.read_text(p), rel, problems):
            found[lab].append(dict(file=rel, line=b, end=e, text=txt))
    idx = {}
    for lab, lst in sorted(found.items()):
        st = status.get(lab)
        pick = None
        if st:
            cands = [x for x in lst if x['file'] == st[0]]
            if cands:
                pick = min(cands, key=lambda x: abs(x['line'] - st[1]))
                if pick['line'] != st[1]:
                    problems.append('%s: FIGURES_STATUS.md gives %s:%d, the BEGIN delimiter is at line %d (block located by '
                                    'its delimiters)' % (lab, st[0], st[1], pick['line']))
            else:
                problems.append('%s: not found in %s named by FIGURES_STATUS.md; using %s' % (lab, st[0], lst[0]['file']))
        if pick is None:
            pick = lst[0]
        if len(lst) > 1:
            texts = set(norm_block(x['text']) for x in lst)
            problems.append('%s: %d blocks in the sources (%s)%s; using %s:%d' % (
                lab, len(lst), ', '.join('%s:%d' % (x['file'], x['line']) for x in lst),
                ' with different contents' if len(texts) > 1 else ' (identical)', pick['file'], pick['line']))
        idx[lab] = pick
    for lab, (f, ln) in sorted(status.items()):
        if lab not in idx:
            problems.append('%s: FIGURES_STATUS.md names %s:%d but no delimiter block exists there' % (lab, f, ln))
    return idx, status


def comment_mask(text):
    """Set of character offsets that lie inside %-comments."""
    mask = []
    off = 0
    for line in text.split('\n'):
        c = B.comment_start(line)
        if c is not None:
            mask.append((off + c, off + len(line)))
        off += len(line) + 1
    return mask


def normalize_ref_lists(text):
    """Remove whitespace (and %-comments) inside label lists of \\cref/\\uses/...; returns (text, count)."""
    mask = comment_mask(text)
    starts = [a for a, b in mask]

    def in_comment(pos):
        import bisect
        i = bisect.bisect_right(starts, pos) - 1
        return i >= 0 and mask[i][0] <= pos < mask[i][1]
    out, last, n = [], 0, 0
    for m in LIST_CMD_RE.finditer(text):
        if in_comment(m.start()):
            continue
        inner = m.group(2)
        if not re.search(r'\s|%', inner):
            continue
        parts = []
        for ln in inner.split('\n'):
            c = B.comment_start(ln)
            parts.append(ln if c is None else ln[:c])
        new = re.sub(r'\s+', '', ''.join(parts))
        if new == inner:
            continue
        new += '%\n' * inner.count('\n')      # keep the line count (line numbers of the copy = those of chapters/)
        out.append(text[last:m.start(2)])
        out.append(new)
        last = m.end(2)
        n += 1
    out.append(text[last:])
    return ''.join(out), n


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--chapters', required=True)
    ap.add_argument('--root', default=None, help='work directory (contains figures/ and research/); default: parent of chapters')
    ap.add_argument('--status', default=None, help='FIGURES_STATUS.md (default <root>/figures/FIGURES_STATUS.md)')
    ap.add_argument('--apply', action='store_true')
    ap.add_argument('--out', default=None, help='output directory of the copy (required with --apply)')
    ap.add_argument('--normalize-refs', action='store_true')
    ap.add_argument('--report', default=None)
    a = ap.parse_args()
    if not os.path.isdir(a.chapters):
        sys.exit('figsync: %s is not a directory' % a.chapters)
    root = a.root or os.path.dirname(os.path.abspath(a.chapters))
    status_path = a.status or os.path.join(root, 'figures', 'FIGURES_STATUS.md')
    if a.apply:
        if not a.out:
            sys.exit('figsync: --apply needs --out')
        if os.path.abspath(a.out) == os.path.abspath(a.chapters):
            sys.exit('figsync: refusing to write into the chapters directory')
    src_problems = []
    idx, status = source_index(root, status_path, src_problems)
    files = sorted(f for f in os.listdir(a.chapters) if f.endswith('.tex'))
    rep = []
    unit_problems = []
    seen = collections.defaultdict(list)
    stats = collections.Counter()
    new_text = {}
    for f in files:
        raw = B.read_text(os.path.join(a.chapters, f))
        blocks = blocks_of(raw, f, unit_problems)
        lines = raw.split('\n')
        repl = []           # (begin, end, new lines)
        for (lab, b, e, txt) in blocks:
            seen[lab].append('%s:%d' % (f, b))
            if lab in B.GENERATED_FIGS:
                repl.append((b, e, ['%% figsync: block %s removed -- generated by blueprint_gen.py (build/appP/)' % lab]))
                rep.append('REMOVED   %-34s %s:%d-%d (generated App P graph)' % (lab, f, b, e))
                stats['removed'] += 1
                continue
            src = idx.get(lab)
            if src is None:
                rep.append('NOSOURCE  %-34s %s:%d-%d (block kept as written)' % (lab, f, b, e))
                stats['nosource'] += 1
                continue
            if norm_block(txt) == norm_block(src['text']):
                stats['same'] += 1
                if txt != src['text']:
                    repl.append((b, e, src['text'].split('\n')))
                continue
            d = first_diff(norm_block(txt), norm_block(src['text']))
            ndiff = sum(1 for x, y in zip(norm_block(txt).split('\n'), norm_block(src['text']).split('\n')) if x != y)
            ndiff += abs(len(norm_block(txt).split('\n')) - len(norm_block(src['text']).split('\n')))
            rep.append('DIFFERS   %-34s %s:%d-%d vs %s:%d  (%d line(s); first at block line %d)\n            unit:   %s\n'
                       '            source: %s' % (lab, f, b, e, src['file'], src['line'], ndiff, d[0], d[1], d[2]))
            repl.append((b, e, src['text'].split('\n')))
            stats['differs'] += 1
        # figure labels outside blocks
        inside = set()
        for (lab, b, e, txt) in blocks:
            inside.update(range(b, e + 1))
        stripped, _ = B.strip_comments(raw)
        for i, line in enumerate(stripped.split('\n'), 1):
            for m in re.finditer(r'\\label\s*\{(fig:[^}]+)\}', line):
                if i not in inside:
                    rep.append('UNBLOCKED %-34s %s:%d (figure label outside a %%%%%% BEGIN/END block)' % (m.group(1), f, i))
                    stats['unblocked'] += 1
        for (b, e, nl) in sorted(repl, reverse=True):
            lines[b - 1:e] = nl
        txt = '\n'.join(lines)
        if a.normalize_refs:
            txt, n = normalize_ref_lists(txt)
            if n:
                rep.append('REFLISTS  %-34s %s: %d label list(s) with spaces/line breaks normalised (cleveref prints ?? otherwise)'
                           % ('', f, n))
                stats['reflists'] += n
        new_text[f] = txt
    for lab, locs in sorted(seen.items()):
        if len(locs) > 1:
            rep.append('DUPLICATE %-34s %s' % (lab, ', '.join(locs)))
            stats['duplicate'] += 1
    out = ['figsync report -- %d unit file(s) in %s; %d figure blocks in the sources' % (len(files), a.chapters, len(idx)),
           'summary: same %d, differs (replaced) %d, generated (removed) %d, no source %d, duplicates %d, labels outside '
           'blocks %d%s' % (stats['same'], stats['differs'], stats['removed'], stats['nosource'], stats['duplicate'],
                           stats['unblocked'], (', normalised label lists %d' % stats['reflists']) if a.normalize_refs else '')]
    out += rep
    if unit_problems:
        out.append('-- delimiter problems in the unit files')
        out += ['  ' + x for x in unit_problems]
    if src_problems:
        out.append('-- notes on the figure sources')
        out += ['  ' + x for x in src_problems]
    if a.apply:
        os.makedirs(a.out, exist_ok=True)
        for f in os.listdir(a.out):
            if f.endswith('.tex') and f not in new_text:
                os.remove(os.path.join(a.out, f))
        for f, t in new_text.items():
            with open(os.path.join(a.out, f), 'w', encoding='utf-8') as fh:
                fh.write(t)
        out.append('applied: %d file(s) written to %s (chapters/ untouched)' % (len(new_text), a.out))
    else:
        out.append('dry run: nothing written (use --apply --out DIR to write the copy)')
    txt = '\n'.join(out) + '\n'
    if a.report:
        with open(a.report, 'w', encoding='utf-8') as fh:
            fh.write(txt)
    sys.stdout.write(txt)


if __name__ == '__main__':
    main()
